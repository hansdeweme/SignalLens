from __future__ import annotations
import json
from dataclasses import asdict, is_dataclass
from pathlib import Path
from typing import Any, Dict


def _to_jsonable(value: Any) -> Any:
    """
    Convert SummaryResult and nested values into something json-serializable.
    """
    if is_dataclass(value):
        return {k: _to_jsonable(v) for k, v in asdict(value).items()}
    if isinstance(value, dict):
        return {str(k): _to_jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_to_jsonable(v) for v in value]
    if isinstance(value, Path):
        return str(value)
    return value

def persist_summary_result(summary_result: Any, output_dir: str | Path, *, flat: bool = False) -> Dict[str, str]:
    """
    Persist SummaryResult into:
      - summary/final_summary.json
      - summary/final_summary.txt
      - summary/final_summary.html
    Returns a dict with the written file paths.
    """
    output_dir = Path(output_dir)
    summary_dir = output_dir if flat else output_dir / "summary"
    summary_dir.mkdir(parents=True, exist_ok=True)
    json_path = summary_dir / "final_summary.json"
    txt_path = summary_dir / "final_summary.txt"
    html_path = summary_dir / "final_summary.html"
    # Structured JSON
    payload = _to_jsonable(summary_result)
    json_path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    # Plain text
    full_text = (summary_result.get("full_text", "") if isinstance(summary_result, dict)
                 else getattr(summary_result, "full_text", "")) or ""
    full_text = _append_generator_to_text(full_text, summary_result)
    txt_path.write_text(full_text, encoding="utf-8")
    # HTML
    full_html = (summary_result.get("full_html", "") if isinstance(summary_result, dict)
                 else getattr(summary_result, "full_html", "")) or ""
    full_html = _append_generator_to_html(full_html, summary_result)
    html_path.write_text(full_html, encoding="utf-8")
    return {
        "final_summary_json": str(json_path),
        "final_summary_txt": str(txt_path),
        "final_summary_html": str(html_path),
    }
    
def _get_generator_text(summary_result: Any) -> str:
    generator = (summary_result.get("generator") if isinstance(summary_result, dict)
                 else getattr(summary_result, "generator", None))
    if generator:
        return str(generator)

    app_metadata = (summary_result.get("app_metadata") if isinstance(summary_result, dict)
                    else getattr(summary_result, "app_metadata", None))
    if isinstance(app_metadata, dict):
        generator = app_metadata.get("generator")
        if generator:
            return str(generator)

    return "Generated by SignalLens"

def _append_generator_to_text(text: str, summary_result: Any) -> str:
    generator = _get_generator_text(summary_result)

    if generator in text:
        return text

    footer = (
        "\n\n"
        + "-" * 72
        + "\n"
        + generator
        + "\n"
    )

    return text.rstrip() + footer

def _append_generator_to_html(html: str, summary_result: Any) -> str:
    generator = _get_generator_text(summary_result)

    if generator in html:
        return html

    footer = f"""
<hr style="margin-top: 32px; border: none; border-top: 1px solid #e5e7eb;">
<p style="font-size: 12px; color: #6b7280; margin-top: 12px;">
    {generator}
</p>
"""

    if "</body>" in html:
        return html.replace("</body>", footer + "\n</body>")

    return html.rstrip() + footer
